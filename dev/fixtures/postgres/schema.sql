COMMENT ON COLUMN article.titre IS 'Titre affiché en une';
COMMENT ON COLUMN article.chapo IS 'Résumé affiché sous le titre';
COMMENT ON COLUMN article.acces IS 'Niveau requis pour lire l''article en entier';
COMMENT ON COLUMN article.vues IS 'Compteur de vues, remis à zéro chaque mois';
COMMENT ON COLUMN article.temps_lecture IS 'Minutes';
COMMENT ON COLUMN article.metadonnees IS 'Balises pour les réseaux sociaux';

-- MySQL's ON UPDATE CURRENT_TIMESTAMP
CREATE FUNCTION touch_modifie_le() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.modifie_le := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER article_touch_modifie_le BEFORE UPDATE ON article
  FOR EACH ROW EXECUTE FUNCTION touch_modifie_le();

