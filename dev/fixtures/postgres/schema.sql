CREATE TYPE article_acces AS ENUM ('libre', 'inscrit', 'abonne');
CREATE TYPE utilisateur_statut AS ENUM ('actif', 'inactif', 'suspendu', 'supprime');
CREATE TYPE formule_periodicite AS ENUM ('mensuel', 'annuel');
CREATE TYPE moyen_paiement_type AS ENUM ('carte', 'prelevement', 'paypal');
CREATE TYPE moyen_paiement_reseau AS ENUM ('visa', 'mastercard', 'amex', 'cb');
CREATE TYPE abonnement_statut AS ENUM ('essai', 'actif', 'impaye', 'suspendu', 'resilie');
CREATE TYPE paiement_statut AS ENUM ('en_attente', 'reussi', 'refuse', 'rembourse');
CREATE TYPE remboursement_motif AS ENUM ('doublon', 'erreur_facturation', 'geste_commercial', 'retractation');
CREATE TYPE commentaire_statut AS ENUM ('en_attente', 'publie', 'masque', 'supprime');
CREATE TYPE signalement_motif AS ENUM ('injure', 'hors_sujet', 'spam', 'desinformation', 'harcelement');
CREATE TYPE signalement_decision AS ENUM ('conserve', 'masque', 'supprime');
CREATE TYPE lecture_source AS ENUM ('accueil', 'rubrique', 'recherche', 'newsletter', 'reseaux', 'moteur', 'notification');
CREATE TYPE lecture_appareil AS ENUM ('ordinateur', 'mobile', 'tablette');
CREATE TYPE newsletter_periodicite AS ENUM ('quotidienne', 'hebdomadaire', 'mensuelle');
CREATE TYPE inscription_origine AS ENUM ('inscription', 'popup', 'pied_de_page', 'offre');

CREATE TABLE auteur (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom varchar(80) NOT NULL,
  prenom varchar(60),
  genre auteur_genre,
  initiale varchar(1) GENERATED ALWAYS AS (left(nom, 1)) STORED,
  email varchar(120),
  role auteur_role NOT NULL DEFAULT 'redacteur',
  service varchar(40),
  biographie text,
  ville varchar(60),
  arrive_le date,
  parti_le date,
  actif boolean NOT NULL DEFAULT true,
  compte_x varchar(40),
  CONSTRAINT uniq_auteur_email UNIQUE (email)
);
COMMENT ON COLUMN auteur.service IS 'Rubrique de rattachement';
COMMENT ON COLUMN auteur.parti_le IS 'NULL tant que la personne est en poste';

CREATE TABLE categorie (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id integer,
  nom varchar(60) NOT NULL,
  slug varchar(60) NOT NULL,
  description varchar(255),
  couleur char(7) NOT NULL DEFAULT '#3b6ea5',
  ordre smallint NOT NULL DEFAULT 0,
  CONSTRAINT uniq_categorie_slug UNIQUE (slug),
