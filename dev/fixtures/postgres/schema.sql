-- "Le Fil": a French news site with subscriptions, as a development dataset.
-- The same tables as mysql/schema.sql, in PostgreSQL's own types: an ENUM column is an enum type, a
-- BOOLEAN is a boolean, an UNSIGNED integer takes the next size up, ON UPDATE CURRENT_TIMESTAMP is a trigger.

DROP TABLE IF EXISTS
  envoi_newsletter, inscription_newsletter, newsletter, lecture, favori, signalement_commentaire,
  commentaire, remboursement, paiement, moyen_paiement, abonnement, code_promo, formule_abonnement,
  utilisateur, article_revision, article_media, article_tag, tag, media, article, dossier, categorie,
  auteur
CASCADE;
DROP TYPE IF EXISTS
  auteur_genre, auteur_role, media_type, media_licence, article_statut, article_acces,
  utilisateur_statut, formule_periodicite, moyen_paiement_type, moyen_paiement_reseau,
  abonnement_statut, paiement_statut, remboursement_motif, commentaire_statut, signalement_motif,
  signalement_decision, lecture_source, lecture_appareil, newsletter_periodicite,
  inscription_origine;
DROP FUNCTION IF EXISTS touch_modifie_le();

