  type media_type NOT NULL DEFAULT 'photo',
  legende varchar(255),
  texte_alternatif varchar(255),
  credit varchar(80),
  licence media_licence NOT NULL DEFAULT 'maison',
  largeur integer,
  hauteur integer,
  poids_octets bigint,
  auteur_id integer,
  importe_le timestamp NOT NULL,
  CONSTRAINT uniq_media_fichier UNIQUE (nom_fichier),
  CONSTRAINT fk_media_auteur FOREIGN KEY (auteur_id) REFERENCES auteur (id)
